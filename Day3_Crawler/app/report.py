"""The data-quality report.

Generated by COUNTING crawl_records, never hand-written. That distinction is
the whole point: a number typed into a markdown file is a claim, while a
number computed from stored rows can be recomputed by a reviewer and checked.

Every percentage uses the same denominator -- the total number of URLs
processed -- because statuses partition the input. That is enforced by the
pipeline's one-URL-one-record invariant, and verified here: the report fails
loudly if the status counts do not sum to the total.

WHAT THE TASK ASKS FOR, AND WHERE IT IS:
  % duplicates + how detected     -> the three-layer duplicates table
  % extraction failed / junk      -> the extraction-failure breakdown, by rule
  % missing/unparseable date      -> the date table, broken down by source
  average length + 5 shortest     -> the length section, with text quoted
"""

from __future__ import annotations

import json
import os
from collections import Counter
from dataclasses import dataclass, field
from datetime import datetime, timezone
from statistics import mean, median

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.config import Config
from app.statuses import (
    BLOCKED_STATUSES,
    DUPLICATE_STATUSES,
    EXTRACTION_FAILURE_STATUSES,
    REFUSED_BEFORE_FETCH_STATUSES,
    CrawlStatus,
)
from app.storage.models import CrawlRecord

# How many of the shortest articles to quote in full. The task says 5.
_SHORTEST_COUNT = 5
# How much of each short article to quote. Long enough to judge whether it is
# garbage, short enough that the report stays readable.
_SHORTEST_EXCERPT_CHARS = 600


@dataclass
class Report:
    generated_at: datetime
    total_urls: int
    counts: dict[str, int]
    stored: int = 0
    # Populated by build(); grouped into sections that mirror the task.
    duplicates: dict = field(default_factory=dict)
    extraction: dict = field(default_factory=dict)
    party_dates: dict = field(default_factory=dict)
    lengths: dict = field(default_factory=dict)
    structure: dict = field(default_factory=dict)
    shortest: list = field(default_factory=list)
    blocked: dict = field(default_factory=dict)
    refused: dict = field(default_factory=dict)
    hosts: dict = field(default_factory=dict)
    integrity: dict = field(default_factory=dict)


def _pct(part: int, whole: int) -> float:
    """Percentage, guarding against a zero denominator.

    Returns 0.0 rather than raising on an empty corpus: a report over zero
    URLs is legitimate (nothing has been crawled yet) and should render, not
    crash.
    """
    return round(100.0 * part / whole, 1) if whole else 0.0


def build(session: Session, config: Config) -> Report:
    """Compute the report from crawl_records."""
    records = session.execute(
        select(CrawlRecord).order_by(CrawlRecord.id)
    ).scalars().all()

    total = len(records)
    counts = Counter(record.status for record in records)

    report = Report(
        generated_at=datetime.now(timezone.utc),
        total_urls=total,
        counts=dict(sorted(counts.items())),
        stored=counts.get(CrawlStatus.STORED.value, 0),
    )

    # ---- integrity check ----
    # The statuses must partition the input. If they do not, every percentage
    # below is computed against a denominator that does not match the parts,
    # and the report is silently wrong. Checked and reported rather than
    # assumed.
    counted = sum(counts.values())
    report.integrity = {
        "total_records": total,
        "sum_of_status_counts": counted,
        "consistent": counted == total,
    }

    # ---- duplicates, by detection layer ----
    dupe_counts = {
        status.value: counts.get(status.value, 0) for status in DUPLICATE_STATUSES
    }
    dupe_total = sum(dupe_counts.values())

    near_records = [
        record
        for record in records
        if record.status == CrawlStatus.DUPLICATE_NEAR.value
        and record.duplicate_similarity is not None
    ]
    # The highest similarity among documents we did NOT call duplicates. If
    # this sits just under the threshold, the threshold is doing real work and
    # a reviewer should know.
    non_dupe_scores = [
        record.duplicate_similarity
        for record in records
        if record.status == CrawlStatus.STORED.value
        and record.duplicate_similarity is not None
    ]

    report.duplicates = {
        "total": dupe_total,
        "pct": _pct(dupe_total, total),
        "by_layer": {
            "url_after_normalisation": {
                "count": dupe_counts.get(CrawlStatus.DUPLICATE_URL.value, 0),
                "pct": _pct(dupe_counts.get(CrawlStatus.DUPLICATE_URL.value, 0), total),
                "method": (
                    "Exact match on the canonical URL after normalisation "
                    "(https forced, tracking params stripped, trailing slash "
                    "and #fragment removed, host lowercased)."
                ),
            },
            "content_sha256": {
                "count": dupe_counts.get(CrawlStatus.DUPLICATE_CONTENT.value, 0),
                "pct": _pct(dupe_counts.get(CrawlStatus.DUPLICATE_CONTENT.value, 0), total),
                "method": (
                    "SHA-256 of the whitespace-normalised article text. "
                    "Catches syndicated copies under different URLs."
                ),
            },
            "near_duplicate": {
                "count": dupe_counts.get(CrawlStatus.DUPLICATE_NEAR.value, 0),
                "pct": _pct(dupe_counts.get(CrawlStatus.DUPLICATE_NEAR.value, 0), total),
                "method": (
                    f"Jaccard similarity over {config.shingle_size}-word shingles, "
                    f"threshold {config.near_duplicate_threshold:.0%}."
                ),
                "matches": [
                    {
                        "url": record.canonical_url,
                        "similarity": record.duplicate_similarity,
                        "duplicate_of_record": record.duplicate_of_id,
                    }
                    for record in near_records
                ],
            },
        },
        "highest_similarity_among_kept": (
            round(max(non_dupe_scores), 4) if non_dupe_scores else None
        ),
    }

    # ---- extraction failures and junk ----
    extraction_failures = sum(
        counts.get(status.value, 0) for status in EXTRACTION_FAILURE_STATUSES
    )

    # Break the junk bucket down by WHICH rule fired. The rule names are
    # written into status_detail as "[rule_a, rule_b] ...", so they can be
    # recovered and counted here.
    rule_counter: Counter[str] = Counter()
    for record in records:
        if record.status != CrawlStatus.JUNK.value or not record.status_detail:
            continue
        detail = record.status_detail
        if detail.startswith("["):
            closing = detail.find("]")
            if closing > 0:
                for rule in detail[1:closing].split(","):
                    rule_counter[rule.strip()] += 1

    report.extraction = {
        "failed_or_junk": extraction_failures,
        "pct": _pct(extraction_failures, total),
        "extraction_failed": {
            "count": counts.get(CrawlStatus.EXTRACTION_FAILED.value, 0),
            "pct": _pct(counts.get(CrawlStatus.EXTRACTION_FAILED.value, 0), total),
            "meaning": "Page fetched, but no article text came out of it.",
        },
        "junk": {
            "count": counts.get(CrawlStatus.JUNK.value, 0),
            "pct": _pct(counts.get(CrawlStatus.JUNK.value, 0), total),
            "meaning": "Text extracted, but it failed a quality rule.",
            "by_rule": dict(rule_counter.most_common()),
        },
        "rules": {
            "too_short": f"fewer than {config.min_article_chars} characters",
            "high_link_density": (
                f"more than {config.max_link_density:.0%} of characters inside <a> tags"
            ),
            "extractor_disagreement": (
                "trafilatura and readability-lxml disagreed on length by more "
                f"than {1 - config.extractor_agreement_ratio:.0%}"
            ),
        },
    }

    # ---- publish dates ----
    # Measured over documents that got far enough to HAVE a date extracted --
    # i.e. those we stored. Counting a robots-disallowed URL as "missing a
    # date" would be meaningless: we never looked at its page.
    stored_records = [r for r in records if r.status == CrawlStatus.STORED.value]
    stored_total = len(stored_records)

    with_date = [r for r in stored_records if r.published_at is not None]
    without_date = [r for r in stored_records if r.published_at is None]
    # A raw string was found but failed to parse or failed the sanity window.
    unparseable = [r for r in without_date if r.published_at_raw]

    source_counter = Counter(
        record.published_at_source for record in with_date if record.published_at_source
    )

    report.party_dates = {
        "scope": "articles that were stored (a date is only meaningful for those)",
        "stored_total": stored_total,
        "with_date": len(with_date),
        "with_date_pct": _pct(len(with_date), stored_total),
        "missing_or_unparseable": len(without_date),
        "missing_or_unparseable_pct": _pct(len(without_date), stored_total),
        "no_date_found_at_all": len(without_date) - len(unparseable),
        "found_but_unparseable": len(unparseable),
        "by_source": dict(source_counter.most_common()),
        "unparseable_examples": [
            {"url": r.canonical_url, "raw_value": r.published_at_raw}
            for r in unparseable[:5]
        ],
    }

    # ---- lengths ----
    lengths = [r.text_chars for r in stored_records if r.text_chars]
    words = [r.text_words for r in stored_records if r.text_words]

    report.lengths = {
        "articles_measured": len(lengths),
        "mean_chars": round(mean(lengths)) if lengths else 0,
        # Median as well as mean: one 40,000-character article drags the mean
        # up and makes the corpus look longer than it is. Reporting both makes
        # that skew visible instead of hiding it.
        "median_chars": round(median(lengths)) if lengths else 0,
        "min_chars": min(lengths) if lengths else 0,
        "max_chars": max(lengths) if lengths else 0,
        "mean_words": round(mean(words)) if words else 0,
    }

    # ---- structure retention ----
    # Added after a reviewer opened a stored article and found its headings
    # missing. "Is the text clean" and "did the article keep its shape" are
    # different questions, and only the first was being measured.
    with_headings = [r for r in stored_records if (r.headings or 0) > 0]
    with_code = [r for r in stored_records if (r.code_blocks or 0) > 0]
    # A long article with no headings is the suspicious case; a 600-character
    # link-blog post legitimately has none.
    long_without_headings = [
        r for r in stored_records
        if (r.headings or 0) == 0 and (r.text_chars or 0) >= 4000
    ]

    report.structure = {
        "articles_with_headings": len(with_headings),
        "articles_with_headings_pct": _pct(len(with_headings), stored_total),
        "total_headings": sum(r.headings or 0 for r in stored_records),
        "articles_with_code_blocks": len(with_code),
        "total_code_blocks": sum(r.code_blocks or 0 for r in stored_records),
        "long_articles_without_headings": [
            {"url": r.canonical_url, "chars": r.text_chars, "source": r.host}
            for r in sorted(long_without_headings, key=lambda r: -(r.text_chars or 0))
        ],
    }

    # ---- the 5 shortest, quoted ----
    # The task predicts these are usually garbage, so they are quoted rather
    # than merely listed: a reviewer can judge for themselves.
    shortest = sorted(stored_records, key=lambda r: r.text_chars or 0)[:_SHORTEST_COUNT]
    report.shortest = [
        {
            "rank": index + 1,
            "chars": record.text_chars,
            "words": record.text_words,
            "title": record.title,
            "url": record.canonical_url,
            "api_document_id": record.api_document_id,
            "published_at": (
                record.published_at.isoformat() if record.published_at else None
            ),
            "link_density": record.link_density,
            "excerpt": (record.text or "")[:_SHORTEST_EXCERPT_CHARS],
            "truncated": len(record.text or "") > _SHORTEST_EXCERPT_CHARS,
        }
        for index, record in enumerate(shortest)
    ]

    # ---- blocked and refused ----
    report.blocked = {
        status.value: {
            "count": counts.get(status.value, 0),
            "pct": _pct(counts.get(status.value, 0), total),
        }
        for status in BLOCKED_STATUSES
    }
    report.refused = {
        status.value: {
            "count": counts.get(status.value, 0),
            "pct": _pct(counts.get(status.value, 0), total),
        }
        for status in REFUSED_BEFORE_FETCH_STATUSES
    }

    # ---- per-host ----
    host_counter = Counter(record.host for record in records if record.host)
    host_stored = Counter(
        record.host for record in stored_records if record.host
    )
    report.hosts = {
        host: {"attempted": count, "stored": host_stored.get(host, 0)}
        for host, count in host_counter.most_common()
    }

    return report


