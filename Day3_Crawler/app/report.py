def to_json(report: Report) -> str:
    payload = {
        "generated_at": report.generated_at.isoformat(),
        "total_urls_processed": report.total_urls,
        "status_counts": report.counts,
        "integrity": report.integrity,
        "duplicates": report.duplicates,
        "extraction": report.extraction,
        "publish_dates": report.party_dates,
        "lengths": report.lengths,
        "structure_retention": report.structure,
        "five_shortest": report.shortest,
        "blocked": report.blocked,
        "refused_before_fetch": report.refused,
        "hosts": report.hosts,
    }
    return json.dumps(payload, indent=2, ensure_ascii=False)


def to_markdown(report: Report, config: Config) -> str:
    """Render the human-readable report.

    Every number here comes from the Report object, which came from counting
    rows. Nothing in this function invents a figure.
    """
    lines: list[str] = []
    add = lines.append

    add("# Data Quality Report")
    add("")
    add(f"Generated: {report.generated_at.strftime('%Y-%m-%d %H:%M UTC')}")
    add("")
    add(
        "Every number below is computed by counting rows in `crawl_records`, "
        "not written by hand. Re-run `report` to regenerate it."
    )
    add("")

    # ---- headline ----
    add("## Summary")
    add("")
    add("| Metric | Value |")
    add("| --- | --- |")
    add(f"| URLs processed | {report.total_urls} |")
    add(f"| Articles stored | {report.stored} ({_pct(report.stored, report.total_urls)}%) |")
    add(f"| Duplicates | {report.duplicates['total']} ({report.duplicates['pct']}%) |")
    add(
        f"| Extraction failed or junk | {report.extraction['failed_or_junk']} "
        f"({report.extraction['pct']}%) |"
    )
    add(
        f"| Missing/unparseable date (of stored) | "
        f"{report.party_dates['missing_or_unparseable']} "
        f"({report.party_dates['missing_or_unparseable_pct']}%) |"
    )
    add(f"| Mean article length | {report.lengths['mean_chars']} chars |")
    add(f"| Median article length | {report.lengths['median_chars']} chars |")
    add("")

    if not report.integrity["consistent"]:
        add(
            f"> **WARNING:** status counts sum to "
            f"{report.integrity['sum_of_status_counts']} but there are "
            f"{report.integrity['total_records']} records. Percentages below "
            "are unreliable."
        )
        add("")

    # ---- status breakdown ----
    add("## Every outcome")
    add("")
    add(
        "Each URL gets exactly one status, so these counts partition the "
        "input and sum to the total."
    )
    add("")
    add("| Status | Count | % |")
    add("| --- | ---: | ---: |")
    for status, count in sorted(report.counts.items(), key=lambda kv: -kv[1]):
        add(f"| `{status}` | {count} | {_pct(count, report.total_urls)}% |")
    add(f"| **total** | **{report.total_urls}** | **100%** |")
    add("")

    # ---- duplicates ----
    add("## Duplicates, and how they were detected")
    add("")
    add(
        f"**{report.duplicates['total']} of {report.total_urls} URLs "
        f"({report.duplicates['pct']}%)** were duplicates."
    )
    add("")
    add("Three independent layers, reported separately because they catch")
    add("different things and have different reliability:")
    add("")
    add("| Layer | Caught | % | How |")
    add("| --- | ---: | ---: | --- |")
    for name, data in report.duplicates["by_layer"].items():
        add(f"| `{name}` | {data['count']} | {data['pct']}% | {data['method']} |")
    add("")

    near = report.duplicates["by_layer"]["near_duplicate"]
    if near["matches"]:
        add("Near-duplicate matches, with their scores:")
        add("")
        add("| URL | Similarity | Duplicate of record |")
        add("| --- | ---: | ---: |")
        for match in near["matches"]:
            add(
                f"| {match['url']} | {match['similarity']:.1%} | "
                f"#{match['duplicate_of_record']} |"
            )
        add("")

    highest = report.duplicates["highest_similarity_among_kept"]
    if highest is not None:
        add(
            f"Highest similarity among articles we KEPT: **{highest:.1%}** "
            f"(threshold {config.near_duplicate_threshold:.0%}). "
        )
        if highest >= config.near_duplicate_threshold - 0.05:
            add(
                "That is close to the threshold, so the threshold is making a "
                "real judgement call on this corpus, not just rubber-stamping."
            )
        else:
            add(
                "That is comfortably below the threshold, so no kept article "
                "is a borderline call."
            )
        add("")

    # ---- extraction ----
    add("## Extraction failures and junk")
    add("")
    add(
        f"**{report.extraction['failed_or_junk']} of {report.total_urls} "
        f"({report.extraction['pct']}%)** either produced no text or produced "
        "text that failed a quality rule."
    )
    add("")
    add("| Outcome | Count | % | Meaning |")
    add("| --- | ---: | ---: | --- |")
    add(
        f"| `extraction_failed` | {report.extraction['extraction_failed']['count']} "
        f"| {report.extraction['extraction_failed']['pct']}% "
        f"| {report.extraction['extraction_failed']['meaning']} |"
    )
    add(
        f"| `junk` | {report.extraction['junk']['count']} "
        f"| {report.extraction['junk']['pct']}% "
        f"| {report.extraction['junk']['meaning']} |"
    )
    add("")

    if report.extraction["junk"]["by_rule"]:
        add("Which rule rejected them (one document can fail several):")
        add("")
        add("| Rule | Times fired | Definition |")
        add("| --- | ---: | --- |")
        for rule, count in report.extraction["junk"]["by_rule"].items():
            definition = report.extraction["rules"].get(rule, "-")
            add(f"| `{rule}` | {count} | {definition} |")
        add("")

    # ---- dates ----
    dates_data = report.party_dates
    add("## Publish dates")
    add("")
    add(f"Scope: {dates_data['scope']} — {dates_data['stored_total']} articles.")
    add("")
    add("| Metric | Count | % of stored |")
    add("| --- | ---: | ---: |")
    add(
        f"| Date found and parsed | {dates_data['with_date']} "
        f"| {dates_data['with_date_pct']}% |"
    )
    add(
        f"| **Missing or unparseable** | **{dates_data['missing_or_unparseable']}** "
        f"| **{dates_data['missing_or_unparseable_pct']}%** |"
    )
    add(f"| — no date on the page at all | {dates_data['no_date_found_at_all']} | |")
    add(f"| — found something, could not parse it | {dates_data['found_but_unparseable']} | |")
    add("")

    if dates_data["by_source"]:
        add("Where the dates actually came from (ladder, most authoritative first):")
        add("")
        add("| Source | Articles |")
        add("| --- | ---: |")
        for source, count in dates_data["by_source"].items():
            add(f"| `{source}` | {count} |")
        add("")

    if dates_data["unparseable_examples"]:
        add("Strings we found but could not turn into a valid date:")
        add("")
        for example in dates_data["unparseable_examples"]:
            add(f"- `{example['raw_value']}` — {example['url']}")
        add("")

    # ---- lengths ----
    add("## Article length")
    add("")
    add("| Metric | Characters |")
    add("| --- | ---: |")
    add(f"| Mean | {report.lengths['mean_chars']} |")
    add(f"| Median | {report.lengths['median_chars']} |")
    add(f"| Shortest | {report.lengths['min_chars']} |")
    add(f"| Longest | {report.lengths['max_chars']} |")
    add("")
    add(f"Mean words per article: {report.lengths['mean_words']}.")
    add("")

    # ---- structure ----
    structure = report.structure
    add("## Structure retained")
    add("")
    add(
        "Clean text is not the whole job: an article stripped down to "
        "undifferentiated paragraphs has lost something too. Extraction "
        "keeps Markdown, so headings and code blocks survive."
    )
    add("")
    add("| Metric | Value |")
    add("| --- | ---: |")
    add(
        f"| Articles with headings | {structure['articles_with_headings']} "
        f"of {dates_data['stored_total']} ({structure['articles_with_headings_pct']}%) |"
    )
    add(f"| Total headings kept | {structure['total_headings']} |")
    add(f"| Articles with code blocks | {structure['articles_with_code_blocks']} |")
    add(f"| Total code blocks kept | {structure['total_code_blocks']} |")
    add("")

    if structure["long_articles_without_headings"]:
        add(
            "Long articles (4,000+ chars) that came out with **no headings** — "
            "these are the ones worth inspecting:"
        )
        add("")
        add("| Article | Chars |")
        add("| --- | ---: |")
        for item in structure["long_articles_without_headings"]:
            add(f"| {item['url']} | {item['chars']} |")
        add("")
        add(
            "Known cause for `research.google`: its headings sit in a "
            "different DOM branch (`div.component-intro`) from its article "
            "body (`div.blog-summary`), so an extractor that selects one "
            "content container cannot associate them. Reported rather than "
            "worked around with a site-specific rule."
        )
        add("")

    # ---- 5 shortest ----
    add(f"## The {len(report.shortest)} shortest articles")
    add("")
    add(
        "The brief predicts these are usually garbage, so they are quoted "
        "here rather than just listed — judge for yourself."
    )
    add("")
    for item in report.shortest:
        add(f"### {item['rank']}. {item['title'] or '(no title)'}")
        add("")
        add(f"- **{item['chars']} chars**, {item['words']} words")
        add(f"- URL: {item['url']}")
        add(f"- Stored as document `#{item['api_document_id']}`")
        add(f"- Publish date: {item['published_at'] or '**none found**'}")
        if item["link_density"] is not None:
            add(f"- Link density: {item['link_density']:.2f}")
        add("")
        add("```text")
        add(item["excerpt"] or "(empty)")
        if item["truncated"]:
            add("...[truncated]")
        add("```")
        add("")

    # ---- blocked ----
    blocked_total = sum(entry["count"] for entry in report.blocked.values())
    add("## Pages we were not allowed to read")
    add("")
    if blocked_total == 0:
        add("None encountered in this run.")
    else:
        add("| Reason | Count | % |")
        add("| --- | ---: | ---: |")
        for status, entry in report.blocked.items():
            if entry["count"]:
                add(f"| `{status}` | {entry['count']} | {entry['pct']}% |")
    add("")
    add(
        "These are detected and reported, never worked around: the brief puts "
        "anything behind a login out of scope."
    )
    add("")

    # ---- refused ----
    refused_total = sum(entry["count"] for entry in report.refused.values())
    add("## URLs we refused before fetching")
    add("")
    if refused_total == 0:
        add("None in this run.")
    else:
        add("| Reason | Count | % |")
        add("| --- | ---: | ---: |")
        for status, entry in report.refused.items():
            if entry["count"]:
                add(f"| `{status}` | {entry['count']} | {entry['pct']}% |")
        add("")
        add(
            "Refusing before the network call means these cost the target "
            "site nothing."
        )
    add("")

    # ---- hosts ----
    if report.hosts:
        add("## Per host")
        add("")
        add("| Host | Attempted | Stored |")
        add("| --- | ---: | ---: |")
        for host, data in report.hosts.items():
            add(f"| {host} | {data['attempted']} | {data['stored']} |")
        add("")

    # ---- thresholds ----
    add("## Thresholds these numbers were measured against")
    add("")
    add("| Setting | Value |")
    add("| --- | --- |")
    add(f"| Minimum article length | {config.min_article_chars} chars |")
    add(f"| Maximum link density | {config.max_link_density} |")
    add(f"| Extractor agreement floor | {config.extractor_agreement_ratio} |")
    add(f"| Near-duplicate threshold | {config.near_duplicate_threshold} |")
    add(f"| Shingle size | {config.shingle_size} words |")
    add(f"| Plausible date range | {config.min_plausible_year} to today+{config.future_date_tolerance_days}d |")
    add("")
    add(
        "Changing any of these changes the numbers above, which is why they "
        "are stated here rather than buried in the code."
    )
    add("")

    return "\n".join(lines)


def write(session: Session, config: Config) -> tuple[str, str]:
    """Build the report and write both formats. Returns the two paths."""
    report = build(session, config)
    os.makedirs(config.report_dir, exist_ok=True)

    md_path = os.path.join(config.report_dir, "REPORT.md")
    json_path = os.path.join(config.report_dir, "report.json")

    with open(md_path, "w", encoding="utf-8") as handle:
        handle.write(to_markdown(report, config))
    with open(json_path, "w", encoding="utf-8") as handle:
        handle.write(to_json(report))

    return md_path, json_path
